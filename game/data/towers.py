def _with_lv45(lv1: TowerStats, lv2: TowerStats, lv3: TowerStats) -> Tuple[TowerStats, ...]:
    """Extend a 3-level progression cleanly to 5 upgrade levels (Lv1..Lv5)."""
    def next_lv(prev: TowerStats, lvl: int, dmg_m: float, cost_m: float, cd_m: float, rng_add: float) -> TowerStats:
        return TowerStats(
            level=lvl,
            cost=int(round((prev.cost * cost_m) / 5.0)) * 5,
            damage=round(prev.damage * dmg_m, 1) if prev.damage > 0 else 0,
            cooldown=round(max(0.08, prev.cooldown * cd_m), 2) if prev.damage > 0 or prev.spike_damage > 0 else prev.cooldown,
            range=round(prev.range + rng_add, 1),
            min_range=prev.min_range,
            splash_radius=round(prev.splash_radius + (0.2 if prev.splash_radius > 0 else 0.0), 1),
            splash_ratio=min(0.95, round(prev.splash_ratio + (0.04 if prev.splash_ratio > 0 else 0.0), 2)),
            slow_factor=min(0.85, round(prev.slow_factor + (0.05 if prev.slow_factor > 0 else 0.0), 2)),
            slow_duration=round(prev.slow_duration + (0.4 if prev.slow_duration > 0 else 0.0), 1),
            stun_duration=round(prev.stun_duration + (0.1 if prev.stun_duration > 0 else 0.0), 2),
            chain_count=prev.chain_count + (1 if prev.chain_count > 0 and lvl == 5 else 0),
            chain_falloff=min(0.95, round(prev.chain_falloff + (0.03 if prev.chain_count > 0 else 0.0), 2)),
            poison_dps=round(prev.poison_dps * 1.45, 1) if prev.poison_dps > 0 else 0,
            poison_duration=round(prev.poison_duration + (0.4 if prev.poison_duration > 0 else 0.0), 1),
            armor_shred=round(prev.armor_shred + (2.0 if prev.armor_shred > 0 else 0.0), 1),
            armor_pierce=min(1.0, round(prev.armor_pierce + (0.1 if 0 < prev.armor_pierce < 1 else 0.0), 2)),
            execute_pct=min(0.35, round(prev.execute_pct + (0.04 if prev.execute_pct > 0 else 0.0), 2)),
            income_per_wave=int(round(prev.income_per_wave * 1.55)) if prev.income_per_wave > 0 else 0,
            income_per_tick=int(round(prev.income_per_tick * 1.50)) if prev.income_per_tick > 0 else 0,
            income_interval=max(2.8, round(prev.income_interval - 0.3, 1)) if prev.income_interval > 0 else 0.0,
            buff_dmg_pct=min(0.75, round(prev.buff_dmg_pct + (0.08 if prev.buff_dmg_pct > 0 else 0.0), 2)),
            buff_spd_pct=min(0.75, round(prev.buff_spd_pct + (0.08 if prev.buff_spd_pct > 0 else 0.0), 2)),
            buff_rng_pct=min(0.65, round(prev.buff_rng_pct + (0.08 if prev.buff_rng_pct > 0 else 0.0), 2)),
            heal_allies_per_sec=round(prev.heal_allies_per_sec * 1.45, 1) if prev.heal_allies_per_sec > 0 else 0.0,
            spawn_ally_kind=prev.spawn_ally_kind,
            spawn_interval=max(2.8, round(prev.spawn_interval * 0.86, 1)) if prev.spawn_interval > 0 else 0.0,
            max_active_allies=prev.max_active_allies + (1 if prev.max_active_allies > 0 and lvl == 5 else 0),
            spike_damage=round(prev.spike_damage * 1.5, 1) if prev.spike_damage > 0 else 0.0,
            spike_charges=prev.spike_charges + (2 if prev.spike_charges > 0 else 0),
        )

    lv4 = next_lv(lv3, 4, 1.50, 1.45, 0.90, 0.4)
    lv5 = next_lv(lv4, 5, 1.55, 1.55, 0.88, 0.5)
    return (lv1, lv2, lv3, lv4, lv5)


def _bp(
    key: str,
    symbol: str,
    name: str,
    rarity: str,
    role: str,
    description: str,
    shot_char: str,
    lv1: TowerStats,
    lv2: TowerStats,
    lv3: TowerStats,
) -> TowerBlueprint:
    return TowerBlueprint(
        key=key,
        symbol=symbol,
        name=name,
        rarity=rarity,
        role=role,
        description=description,
        shot_char=shot_char,
        levels=_with_lv45(lv1, lv2, lv3),
    )


