#!/usr/bin/env python3
"""Export Python game data catalogs into ios/TerminalTD/www/data.js."""

from __future__ import annotations

from dataclasses import asdict
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from game.data.banners import BANNERS, BANNER_ORDER  # noqa: E402
from game.data.difficulties import DIFFICULTIES, DIFFICULTY_ORDER  # noqa: E402
from game.data.maps import MAPS  # noqa: E402
from game.data.progression import (  # noqa: E402
    FUSION_RECIPES,
    RARITY_STAR_MULT,
    SACRIFICE_PERKS,
    STAR_BASE_COSTS,
)
from game.data.rarities import RARITIES, RARITY_ORDER, STARTING_COINS  # noqa: E402
from game.data.towers import STARTER_LOADOUT, TOWER_BLUEPRINTS, TOWER_ORDER  # noqa: E402
from game.data.units import ALLY_TEMPLATES, UNIT_ORDER, UNIT_TEMPLATES  # noqa: E402
from game.data.waves import WAVE_DEFINITIONS  # noqa: E402
from game.models import (  # noqa: E402
    GRID_HEIGHT,
    GRID_WIDTH,
    MAX_LOADOUT,
    MAX_PERK_LOADOUT,
    MAX_UNIT_STAR,
)


def main() -> None:
    maps_out = []
    for m in MAPS:
        meta_path, centerline, road_set, spawn_cells, base_cells = m.build_geometry()
        maps_out.append(
            {
                "key": m.key,
                "name": m.name,
                "description": m.description,
                "meta_waypoints": m.meta_waypoints,
                "centerline": centerline,
                "road_cells": sorted([list(c) for c in road_set]),
                "spawn_cells": sorted([list(c) for c in spawn_cells]),
                "base_cells": sorted([list(c) for c in base_cells]),
            }
        )

    payload = {
        "GRID_WIDTH": GRID_WIDTH,
        "GRID_HEIGHT": GRID_HEIGHT,
        "MAX_LOADOUT": MAX_LOADOUT,
        "MAX_PERK_LOADOUT": MAX_PERK_LOADOUT,
        "MAX_UNIT_STAR": MAX_UNIT_STAR,
        "STARTING_COINS": STARTING_COINS,
        "STARTER_LOADOUT": list(STARTER_LOADOUT),
        "FUSION_RECIPES": [asdict(r) for r in FUSION_RECIPES],
        "SACRIFICE_PERKS": [asdict(p) for p in SACRIFICE_PERKS],
        "STAR_BASE_COSTS": STAR_BASE_COSTS,
        "RARITY_STAR_MULT": RARITY_STAR_MULT,
        "RARITY_ORDER": list(RARITY_ORDER),
        "RARITIES": {k: asdict(v) for k, v in RARITIES.items()},
        "BANNER_ORDER": list(BANNER_ORDER),
        "BANNERS": {k: asdict(v) for k, v in BANNERS.items()},
        "DIFFICULTY_ORDER": list(DIFFICULTY_ORDER),
        "DIFFICULTIES": {k: asdict(v) for k, v in DIFFICULTIES.items()},
        "TOWER_ORDER": list(TOWER_ORDER),
        "TOWERS": {k: asdict(v) for k, v in TOWER_BLUEPRINTS.items()},
        "UNIT_ORDER": list(UNIT_ORDER),
        "UNITS": {k: asdict(v) for k, v in UNIT_TEMPLATES.items()},
        "ALLIES": {k: asdict(v) for k, v in ALLY_TEMPLATES.items()},
        "MAPS": maps_out,
        "WAVES": [
            [[kind, count, interval] for kind, count, interval in wave]
            for wave in WAVE_DEFINITIONS
        ],
    }

    out_path = os.path.join(ROOT, "ios", "TerminalTD", "www", "data.js")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by scripts/export_web_data.py\n")
        f.write("window.TD_DATA = ")
        json.dump(payload, f, separators=(",", ":"))
        f.write(";\n")
    print(f"Wrote {out_path} ({os.path.getsize(out_path)} bytes)")


if __name__ == "__main__":
    main()
